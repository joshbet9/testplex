package nautilus.game.arcade.managers.lobby.legacy;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.FileWriter;
import java.io.IOException;
import java.util.Arrays;

import net.minecraft.server.v1_8_R3.Chunk;
import net.minecraft.server.v1_8_R3.ChunkSection;
import org.bukkit.Location;
import org.bukkit.Material;
import org.bukkit.World;
import org.bukkit.craftbukkit.v1_8_R3.CraftChunk;
import org.bukkit.entity.Creature;
import org.bukkit.entity.Entity;
import org.bukkit.entity.Slime;

/**
 * Generates a simple, repeatable 100x100 test lobby when the real Arcade
 * lobby world has not been provisioned. It deliberately leaves NEW.dat absent,
 * so Arcade continues to use the legacy kit/team datapoints. The isolated test
 * region is reset at chunk-section level to avoid millions of block writes.
 */
public final class TestLobbyPlaneBuilder
{
	private static final int MIN = -50;
	private static final int MAX = 50;
	private static final int CLEAR_MIN = -80;
	private static final int CLEAR_MAX = 80;
	private static final int FLOOR_Y = 100;
	private static final String MARKER = "world/TEST_LOBBY_PLANE.dat";

	private TestLobbyPlaneBuilder()
	{
	}

	public static void ensure(World world)
	{
		if (world == null)
		{
			System.err.println("Test lobby plane skipped: world was not loaded.");
			return;
		}

		File marker = new File(MARKER);
		if (marker.isFile())
		{
			try (BufferedReader reader = new BufferedReader(new FileReader(marker)))
			{
				if ("TESTPLEX_SANDBOX_LOBBY_V3".equals(reader.readLine()))
				{
					return;
				}
			}
			catch (IOException e)
			{
				System.err.println("Could not read previous lobby marker; rebuilding the isolated test plane.");
			}
			System.out.println("Updating an older/incomplete test lobby to the current isolated sky-plane layout.");
		}

		System.out.println("Creating one-time 100x100 Arcade test lobby plane in world at Y=" + FLOOR_Y + ".");
		System.out.println("This is a simple cosmetics/test lobby; the kit and team datapoints remain owned by LegacyGameLobbyManager.");

		// The area spans exactly ten chunks per axis. Clearing every block
		// through Bukkit causes millions of synchronous block writes and can
		// stall the entire legacy server during plugin enable. Reset the chunk
		// sections directly, then recompute their height maps/lighting and put
		// back only the 100x100 platform. This is confined to X/Z -80..79.
		int firstChunk = CLEAR_MIN >> 4;
		int lastChunk = (CLEAR_MAX - 1) >> 4;
		for (int chunkX = firstChunk; chunkX <= lastChunk; chunkX++)
		{
			for (int chunkZ = firstChunk; chunkZ <= lastChunk; chunkZ++)
			{
				Chunk chunk = ((CraftChunk) world.getChunkAt(chunkX, chunkZ)).getHandle();
				ChunkSection[] sections = chunk.getSections();
				for (int section = 0; section < sections.length; section++)
				{
					sections[section] = null;
				}
				Arrays.fill(chunk.heightMap, 0);
				chunk.tileEntities.clear();
				chunk.initLighting();
				chunk.e();
			}
		}

		for (int x = MIN; x < MAX; x++)
		{
			for (int z = MIN; z < MAX; z++)
			{
				world.getBlockAt(x, FLOOR_Y - 2, z).setType(Material.BEDROCK, false);
				world.getBlockAt(x, FLOOR_Y - 1, z).setType(Material.STONE, false);
				world.getBlockAt(x, FLOOR_Y, z).setType(Material.GRASS, false);
			}
		}

		// Remove natural creatures in the test area. Players and plugin-owned
		// non-creature entities are not touched.
		for (Entity entity : world.getEntities())
		{
			Location location = entity.getLocation();
			if (location.getBlockX() >= CLEAR_MIN && location.getBlockX() < CLEAR_MAX
					&& location.getBlockZ() >= CLEAR_MIN && location.getBlockZ() < CLEAR_MAX
					&& location.getBlockY() <= 255
					&& (entity instanceof Creature || entity instanceof Slime))
			{
				entity.remove();
			}
		}

		world.setTime(6000L);
		world.setStorm(false);
		world.setThundering(false);
		world.setGameRuleValue("doDaylightCycle", "false");
		world.setGameRuleValue("doMobSpawning", "false");
		world.setSpawnLocation(0, 104, 0);

		try
		{
			File parent = marker.getParentFile();
			if (parent != null && !parent.isDirectory() && !parent.mkdirs())
			{
				throw new IOException("Could not create marker directory " + parent);
			}
			try (FileWriter writer = new FileWriter(marker))
			{
				writer.write("TESTPLEX_SANDBOX_LOBBY_V3\nGenerated by TestLobbyPlaneBuilder; 100x100 surface; Y=100; void buffer=30\n");
			}
		}
		catch (IOException e)
		{
			throw new RuntimeException("Could not mark generated test lobby plane", e);
		}

		System.out.println("Created flat Arcade test lobby plane: X/Z -50..49, surface Y=100, with the old terrain hollowed out and a 30-block void buffer.");
	}
}
